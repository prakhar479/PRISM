#!/usr/bin/env python
"""DEV: verify and merge a results bundle into runs/, then regenerate RESULTS_INDEX.md (and tables, if requested).

    python scripts/ingest_results.py incoming/RT1/release1_20261101_120000.tar.gz [--tables] [--allow-untagged]

Checks: bundle sha256 file, every file's sha256 against BUNDLE_MANIFEST.json, safe archive paths, manifest and
per_pair.parquet schemas, the run's git commit carries a run-* tag in this repository, no tiny-model runs, and no
duplicates (a run directory that already exists is refused unless byte-identical).
"""
import argparse
import hashlib
import json
import shutil
import sys
import tarfile
import tempfile
import time
from pathlib import Path

import _bootstrap  # noqa: F401
import pandas as pd

from harness import provenance
from harness.profile import REPO_ROOT, load_profile
from harness.schema import validate_manifest, validate_per_pair


def sha256(p: Path) -> str:
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 22), b""):
            h.update(b)
    return h.hexdigest()


def tagged(commit: str) -> list:
    return [t for t in provenance.git("tag", "--points-at", commit).split() if t.startswith("run-")]


def safe_extract(tar: Path, dest: Path) -> None:
    with tarfile.open(tar) as tf:
        for m in tf.getmembers():
            p = Path(m.name)
            if p.is_absolute() or ".." in p.parts or m.issym() or m.islnk():
                raise ValueError(f"unsafe path in bundle: {m.name}")
        tf.extractall(dest, filter="data")


def write_index(runs_root: Path) -> Path:
    rows = []
    for man in sorted(runs_root.glob("E*/*/manifest.json")):
        m = json.loads(man.read_text())
        pp = man.parent / "per_pair.parquet"
        rows.append({"exp_id": m["exp_id"], "name": m["config"].get("name"), "run_hash": m["run_hash"],
                     "status": m["status"], "smoke": m["smoke"], "commit": m["git"]["commit"][:10],
                     "tags": ",".join(tagged(m["git"]["commit"])), "created": m.get("created", ""),
                     "rows": len(pd.read_parquet(pp, columns=["pair_id"])) if pp.exists() else 0,
                     "machine": m["machine"].get("gpu_name") or m["machine"].get("device")})
    lines = ["# RESULTS_INDEX (generated by scripts/ingest_results.py; do not edit)", "",
             "Smoke runs test plumbing and are never results.", "",
             "| exp | name | run | status | smoke | commit | tags | created | per-pair rows | machine |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    lines += [f"| {r['exp_id']} | {r['name']} | `{r['run_hash']}` | {r['status']} | {r['smoke']} | {r['commit']} | {r['tags']} | "
              f"{r['created']} | {r['rows']} | {r['machine']} |" for r in rows]
    out = REPO_ROOT / "RESULTS_INDEX.md" if runs_root.resolve() == (REPO_ROOT / "runs").resolve() else runs_root / "RESULTS_INDEX.md"
    out.write_text("\n".join(lines) + "\n")
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("bundle")
    ap.add_argument("--profile", default="dev")
    ap.add_argument("--allow-untagged", action="store_true", help="accept runs whose commit has no run-* tag (logged)")
    ap.add_argument("--tables", action="store_true", help="regenerate tables/ afterwards")
    a = ap.parse_args(argv)
    bundle = Path(a.bundle)
    shaf = bundle.with_name(bundle.name + ".sha256")
    if not shaf.exists() or shaf.read_text().split()[0] != sha256(bundle):
        print(f"REFUSED: missing or wrong checksum file {shaf.name}")
        return 1
    prof = load_profile(a.profile)
    runs_root = prof.root("runs_root")
    errors, merged, skipped = [], [], []
    with tempfile.TemporaryDirectory() as td:
        td = Path(td)
        safe_extract(bundle, td)
        top = next(td.iterdir())
        bm = json.loads((top / "BUNDLE_MANIFEST.json").read_text())
        for rel, info in bm["files"].items():
            f = top / rel
            if not f.exists() or sha256(f) != info["sha256"]:
                errors.append(f"checksum mismatch: {rel}")
        run_dirs = sorted({(top / rel).parent for rel in bm["files"] if rel.endswith("manifest.json") and rel.startswith("runs/E")})
        for d in run_dirs:
            m = json.loads((d / "manifest.json").read_text())
            errs = validate_manifest(m)
            if not tagged(m["git"]["commit"]) and not a.allow_untagged:
                errs.append(f"commit {m['git']['commit'][:10]} has no run-* tag here")
            if (d / "per_pair.parquet").exists():
                errs += validate_per_pair(pd.read_parquet(d / "per_pair.parquet"))
            elif m["status"] == "complete":
                errs.append("complete run without per_pair.parquet")
            if errs:
                errors += [f"{d.relative_to(top)}: {e}" for e in errs]
        if errors:
            print("REFUSED:\n  " + "\n  ".join(errors[:50]))
            return 1
        for d in run_dirs:
            rel = d.relative_to(top / "runs")
            dest = runs_root / rel
            if dest.exists():
                same = all((dest / f.relative_to(d)).exists() and sha256(dest / f.relative_to(d)) == sha256(f)
                           for f in d.rglob("*") if f.is_file())
                if not same:
                    errors.append(f"duplicate run {rel} with different content")
                skipped.append(str(rel))
                continue
            shutil.copytree(d, dest)
            merged.append(str(rel))
        for sub in ("preflight",):
            if (top / sub).exists():
                shutil.copytree(top / sub, REPO_ROOT / "incoming" / bm["bundle"] / sub, dirs_exist_ok=True)
        q = top / "runs" / "_queue"
        if q.exists():
            shutil.copytree(q, REPO_ROOT / "incoming" / bm["bundle"] / "queue", dirs_exist_ok=True)
    log = runs_root / "_ingested.jsonl"
    log.parent.mkdir(parents=True, exist_ok=True)
    with open(log, "a") as f:
        f.write(json.dumps({"bundle": bm["bundle"], "time": provenance.now(), "merged": merged, "skipped": skipped,
                            "errors": errors, "allow_untagged": a.allow_untagged}) + "\n")
    idx = write_index(runs_root)
    print(f"merged {len(merged)}, already present {len(skipped)}, errors {len(errors)} -> {idx.name}")
    if errors:
        print("  " + "\n  ".join(errors))
        return 1
    if a.tables:
        import subprocess
        subprocess.run([sys.executable, "scripts/make_tables.py"], cwd=REPO_ROOT, check=False)
    return 0


if __name__ == "__main__":
    sys.exit(main())
