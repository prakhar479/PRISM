#!/usr/bin/env python
"""Generate the batch-2 experiment configs (configs/batch2/*.yaml; docs/NEXT_BATCH_PLAN.md). Edit this script, not the YAML.

    python scripts/make_batch2_configs.py            # write + validate
    python scripts/make_batch2_configs.py --check    # fail if a file is out of date

Branch batch2-atlas (queue/pilot-x1-server.yaml): H3, H4, H5 -- where does the causal state go across depth and dictionaries?
  P20  Gemma 3 1B   depth atlas: people-cities, object tracking, IOI x 26 layers x Gemma Scope 2 16k small / big
  P21  Gemma 2 2B   depth atlas: running sum, people-cities, object tracking, IOI x 12 layers x 16k / 65k
  P22  Gemma 3 1B-IT refusal depth atlas: 26 layers x 16k small / big (difference of means vs DAS)
  P28  Gemma 3 1B   width x sparsity grid at L7 / 13 / 17 / 22: 16k / 65k / 262k x small / medium / big (36 dictionaries)
Branch batch2-repair (queue/pilot-x2-server.yaml): H1, H2, H5, H6 -- can a task-agnostic sensitivity subspace repair the task?
  P23  Gemma 2 2B   repair curves at the canonical cells (RS L18, PC L12, OT L12; 16k): var / fis / sens / rnd, predicted and oracle
  P24  Gemma 2 2B   the same at 65k
  P25  Gemma 2 2B   layer sweep (6 / 12 / 18 / 24) of sens vs var vs rnd at k = 32
  P26  Gemma 3 1B   replicate: people-cities, object tracking, IOI at L13 / L17
  P27  Gemma 2 2B   decoder vs information (clin, mlp, cmlp) and KL fine-tuning with / without the sens add-on
Protocol (docs/FINDINGS_CATALOGUE.md S10): DAS v2 with the kl objective, held-out split, 3 independent init seeds, rank-matched
random nulls, a stated write-back operator (subspace); capture and gap are computed per seed by scripts/make_atlas.py / make_repair.py.
"""
import argparse
import sys

import yaml

import _bootstrap  # noqa: F401
import make_pilot_configs as MP
from harness.profile import REPO_ROOT

OUT = REPO_ROOT / "configs" / "batch2"
G2_GENERIC = {"set": "generic/pile10k_6000x128_skip100.json", "skip_positions": 4}
G3_GENERIC = {"set": "generic/pile10k_6000x128_skip100_g3.json", "skip_positions": 4}
G2_PS = {"add_chain": MP.PS["add_chain"], "people_cities": MP.PS["people_cities"], "entity_track": MP.PS["ot_p11"],
         "ioi_control": "prompt_sets/ioi_control_pilot.jsonl.gz"}
G3_PS = {"people_cities": "prompt_sets/people_cities_p1_g3.jsonl.gz", "entity_track": "prompt_sets/entity_track_p11_g3.jsonl.gz",
         "ioi_control": "prompt_sets/ioi_control_x1_g3.jsonl.gz", "refusal": "prompt_sets/refusal_p13_g3it.jsonl.gz"}
NOTE = "batch 2 (docs/NEXT_BATCH_PLAN.md): exploratory, post hoc; generated by scripts/make_batch2_configs.py"
DAS3 = [f"das8v2_kl_s{s}" for s in (0, 1, 2)]


def base(exp_id, name, description, prompt_sets, model="gemma-2-2b", **kw):
    rev = {"gemma-2-2b": MP.REV, "gemma-3-1b-pt": MP.G3_REV, "gemma-3-1b-it": MP.IT_REV}[model]
    d = {"exp_id": exp_id, "name": name, "description": description, "model_revision": rev, "prompt_sets": prompt_sets,
         "n_train": 300, "n_test": 150, "filters": ["f_pilot"], "fit_filter": "f_pilot", "bootstrap": 1000, "seed": 0,
         "notes": [NOTE]}
    if model != "gemma-2-2b":
        d["model"] = model
    d.update(kw)
    return d


def cell(task, layer, sae):
    """A cell with the right family restriction for the task (people-cities: pc_en; object tracking: the three dest families)."""
    if task == "people_cities":
        return MP.pc(layer, sae)
    if task == "entity_track":
        return MP.ot(layer, sae)
    if task == "add_chain":
        return MP.rs(layer, sae)
    return {"task": task, "layer": layer, "sae": sae, "role": "exploratory"}          # ioi_control / refusal: the pilot family


def directions(estimators, ranks=(8,), seeds=5, r_max=8, conds=("feat_A_along_U", "full_along_U")):
    return {"conditions": list(conds), "ranks": list(ranks), "estimators": list(estimators), "sources": ["same_task"],
            "random_seeds": seeds, "r_max": r_max}


# --------------------------------------------------------------------------- the add-on grids of the repair branch
FAMILIES = ("var", "fis", "sens", "rnd")


def addons(ks, families=FAMILIES, oracle=True, extra=()):
    """Add-on names: predicted and (optionally) oracle form of every family at every k, plus `extra`."""
    out = []
    for fam in families:
        for k in ks:
            out.append(f"{fam}{k}")
    if oracle:
        for fam in families:
            for k in ks:
                out.append(f"o{fam}{k}")
    return out + list(extra)


def repair_cells(tasks_layers, widths, mode_list, dict_for):
    """tasks_layers: [(task, layer)]; every (task, layer, width) gets the base dictionary, then each add-on in mode_list."""
    cells = []
    for task, L in tasks_layers:
        for w in widths:
            sae = dict_for(L, w)
            cells.append(cell(task, L, dict(sae)))
            cells += [cell(task, L, {**sae, "addon": m}) for m in mode_list]
    return cells


def g2(L, w="16k"):
    return MP.gs(L, w)


def configs() -> dict:
    out = {}
    # ======================================================================= branch batch2-atlas
    # ---- P20: Gemma 3 1B depth atlas
    cells = []
    for L in range(26):
        for task in ("people_cities", "entity_track", "ioi_control"):
            for l0 in ("small", "big"):
                cells.append(cell(task, L, {"dict": f"gs2_1b_all_L{L}_16k_{l0}"}))
    out["P20"] = base("P20", "depth_atlas_gemma3",
                      "Gemma 3 1B, every layer (0-25), Gemma Scope 2 16k at its small and big L0: how much of the task variable's causal "
                      "subspace do the features carry, by depth, task and sparsity? DAS v2 (kl, rank 8) with 3 independent seeds, "
                      "held-out validity, 5 random-subspace nulls per cell. People-cities, object tracking (three box vocabularies), IOI.",
                      {k: G3_PS[k] for k in ("people_cities", "entity_track", "ioi_control")}, model="gemma-3-1b-pt", cells=cells,
                      conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA"], directions=directions(DAS3))
    # ---- P21: Gemma 2 2B depth atlas
    cells = []
    for L in range(2, 25, 2):
        for task in ("add_chain", "people_cities", "entity_track", "ioi_control"):
            for w in ("16k", "65k"):
                cells.append(cell(task, L, g2(L, w)))
    out["P21"] = base("P21", "depth_atlas_gemma2",
                      "Gemma 2 2B, layers 2-24 in steps of 2, Gemma Scope 16k and 65k (L0 matched): the same atlas as P20 on the model "
                      "the first study used. Running sum, people-cities, object tracking, IOI. DAS v2 (kl, rank 8), 3 seeds.",
                      G2_PS, cells=cells, conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA"], directions=directions(DAS3))
    # ---- P22: refusal depth atlas (instruction-tuned)
    cells = []
    for L in range(26):
        for l0 in ("small", "big"):
            cells.append(cell("refusal", L, {"dict": f"gs2_1bit_all_L{L}_16k_{l0}"}))
    out["P22"] = base("P22", "refusal_atlas_it",
                      "Gemma 3 1B-IT, harmful vs harmless minimal chat pairs, every layer, Gemma Scope 2 16k small / big: is the refusal "
                      "direction (difference of means) and its DAS subspace carried by SAE features at every depth?",
                      {"refusal": G3_PS["refusal"]}, model="gemma-3-1b-it", cells=cells,
                      conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA"],
                      directions=directions(["diffmean", "das1v2_kl_s0", "das1v2_kl_s1", "das4v2_kl_s0"], ranks=(1, 4), r_max=4))
    # ---- P28: Gemma 3 width x sparsity grid at four depths
    cells = []
    for L in (7, 13, 17, 22):
        for task in ("people_cities", "entity_track", "ioi_control"):
            for w in ("16k", "65k", "262k"):
                for l0 in ("small", "medium", "big"):
                    cells.append(cell(task, L, {"dict": f"gs2_1b_L{L}_{w}_{l0}"}))
    out["P28"] = base("P28", "width_sparsity_grid_gemma3",
                      "Gemma 3 1B at layers 7 / 13 / 17 / 22: Gemma Scope 2 residual SAEs at 3 widths x 3 sparsities (36 dictionaries): what "
                      "moves capture, width or L0, and does it depend on depth? Shares the DAS rotations of P20. (At these layers the "
                      "all-layers dictionaries of P20 are independently trained replicates.)",
                      {k: G3_PS[k] for k in ("people_cities", "entity_track", "ioi_control")}, model="gemma-3-1b-pt", cells=cells,
                      conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA"], directions=directions(DAS3))
    # ======================================================================= branch batch2-repair
    canon = [("add_chain", 18), ("people_cities", 12), ("entity_track", 12)]
    d_conds = ["feat_A_errB", "feat_A_meanPos", "feat_B_errA"]
    # ---- P23: repair curves, 16k
    out["P23"] = base("P23", "repair_curves_gemma2_16k",
                      "H1: repair the task variable with a k-dimensional, LINEARLY PREDICTED piece of the SAE error whose subspace is chosen "
                      "from generic text only: by error variance (var), output sensitivity (fis), their product (sens) or at random (rnd); "
                      "each also as an oracle projection of the true error (o*). Gemma 2 2B, 16k, RS L18 / PC L12 / OT L12, k = 2, 8, 32, 128.",
                      G2_PS, cells=repair_cells(canon, ["16k"], ["lin"] + addons((2, 8, 32, 128)), g2), generic=G2_GENERIC,
                      conditions=d_conds, directions=directions(DAS3))
    # ---- P24: 65k
    out["P24"] = base("P24", "repair_curves_gemma2_65k",
                      "P23 at 65k (L0 matched to the 16k cell): do the subspaces that repair a 16k SAE also repair a wider one? var / sens / "
                      "rnd and the sens oracle at k = 8, 32.",
                      G2_PS, cells=repair_cells(canon, ["65k"], ["lin"] + addons((8, 32), ("var", "sens", "rnd"), oracle=False, extra=["osens8", "osens32"]), g2),
                      generic=G2_GENERIC, conditions=d_conds, directions=directions(DAS3))
    # ---- P25: layer sweep
    sweep = [(t, L) for L in (6, 12, 18, 24) for t in ("add_chain", "people_cities", "entity_track")]
    out["P25"] = base("P25", "repair_layer_sweep_gemma2",
                      "Does the sensitivity subspace repair at every depth? sens32 vs var32 vs rnd32 and the sens32 oracle, layers 6 / 12 / 18 / 24, "
                      "running sum, people-cities, object tracking (Gemma 2 2B, 16k).",
                      G2_PS, cells=repair_cells(sweep, ["16k"], ["var32", "sens32", "rnd32", "osens32"], g2), generic=G2_GENERIC,
                      conditions=d_conds, directions=directions(DAS3))
    # ---- P26: Gemma 3 replicate
    g3sweep = [(t, L) for L in (13, 17) for t in ("people_cities", "entity_track", "ioi_control")]
    out["P26"] = base("P26", "repair_gemma3",
                      "H5: P23's design on Gemma 3 1B (Gemma Scope 2 16k medium, L13 / L17): var / sens / rnd and the sens oracle at k = 8, 32.",
                      {k: G3_PS[k] for k in ("people_cities", "entity_track", "ioi_control")}, model="gemma-3-1b-pt",
                      cells=repair_cells(g3sweep, ["16k"], ["lin"] + addons((8, 32), ("var", "sens", "rnd"), oracle=False, extra=["osens8", "osens32"]),
                                         lambda L, w: {"dict": f"gs2_1b_L{L}_16k_medium"}),
                      generic=G3_GENERIC, conditions=d_conds, directions=directions(DAS3))
    # ---- P27: decoder vs information, KL fine-tune
    cells = []
    for task, L in canon:
        sae = g2(L)
        kl = {"dict": f"trained:klft_L{L}_16k", "width": "16k"}
        cells += [cell(task, L, dict(sae)), cell(task, L, {**sae, "addon": "lin"}), cell(task, L, {**sae, "addon": "clin"}),
                  cell(task, L, {**sae, "addon": "mlp1024"}), cell(task, L, {**sae, "addon": "cmlp1024"}),
                  cell(task, L, {**sae, "addon": "sens32"}), cell(task, L, dict(kl)), cell(task, L, {**kl, "addon": "sens32"})]
    out["P27"] = base("P27", "decoder_vs_information",
                      "H2 / H6: is the missing part a decoder problem (clin: the decoder refit on the frozen codes; cmlp: a network on the codes) or "
                      "an information problem (mlp: a network on x as the reference)? And does the sens add-on stack with KL+MSE fine-tuning "
                      "(trained klft dictionaries)? Gemma 2 2B, 16k, canonical cells.",
                      G2_PS, cells=cells, generic=G2_GENERIC, conditions=d_conds, directions=directions(DAS3))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    bad = []
    for k, d in configs().items():
        text = "# GENERATED by scripts/make_batch2_configs.py: edit the script, not this file\n" + yaml.safe_dump(d, sort_keys=False, width=140)
        p = OUT / f"{k}.yaml"
        if a.check:
            if not p.exists() or p.read_text() != text:
                bad.append(p.name)
            continue
        p.write_text(text)
        from harness.config import ExpConfig
        ExpConfig.load(p)                                   # validates
        print(f"{p.relative_to(REPO_ROOT)}: {len(d['cells'])} cells")
    if bad:
        print("out of date:", bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
