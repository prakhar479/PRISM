#!/usr/bin/env python
"""Write the E4 (matched-L0 widths) and E5 (subthreshold) configs from configs/sae_inventory.json, so no L0 list is
hardcoded.

    python scripts/make_e4_config.py                # -> configs/experiments/E4.yaml, E4_1m.yaml, E5.yaml
    python scripts/make_e4_config.py --check        # exit 1 if the committed files differ (tests use this)

Rule (DECISIONS 2026-11-03): the target L0 of a cell is the pilot's 16k variant at that layer (the canonical one,
L0 closest to 100). For every other width at that layer, harness.sae.match_l0 picks the variant closest to the target
in log-L0. For the primary task (object tracking) the nearest variants below and above the target are added
(bracketing), so the analysis can interpolate. Secondary tasks get the closest variant only. 1m goes to a separate
config (E4_1m.yaml): it needs ~9.7 GB of host RAM in bf16 and is run only if time permits (handoff 9, E4).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import _bootstrap  # noqa: F401

from harness.sae import canonical_l0, match_l0, parse_width

ROOT = Path(__file__).resolve().parents[1]
MODEL_REVISION = "c5ebcd40d208330abc697524c919956e692655cf"
# (task, layer, bracket?, role of the non-16k cells)
CELLS = [("entity_track", 12, True), ("add_chain", 18, False), ("ioi_control", 12, False)]
SEPARATE = {"1m"}                      # widths that get their own config


def variants_for(inv: dict, layer: int, bracket: bool) -> list:
    """[(width, l0, why)] for one layer, 16k first, widths in increasing order."""
    ws = inv[str(layer)]
    target = canonical_l0(ws["16k"])
    out = [("16k", target, "pilot (canonical)")]
    for w in sorted((w for w in ws if w != "16k"), key=parse_width):
        m = match_l0(target, ws[w])
        picks = {m["closest"]: "closest"}
        if bracket:
            for side in ("below", "above"):
                if m[side] is not None:
                    picks.setdefault(m[side], f"bracket-{side}")
        out += [(w, l0, why) for l0, why in sorted(picks.items())]
    return out


def render(inv_meta: dict, only: set, exclude: set, exp_id: str, name: str, header: str) -> str:
    inv = inv_meta["inventory"]
    lines = [f"# {header}", "# GENERATED by scripts/make_e4_config.py from configs/sae_inventory.json "
             f"(revision {inv_meta['revision'][:12]}); edit the script, not this file.",
             f"exp_id: {exp_id}", f"name: {name}",
             "description: Gap and repair across SAE widths at L0 matched to the pilot 16k variant (nominal L0 from the "
             "variant name; realized L0 on patched positions and on generic text is recorded per cell).",
             f"model_revision: {MODEL_REVISION}",
             "prompt_sets: {entity_track: prompt_sets/entity_track_pilot.jsonl.gz, add_chain: prompt_sets/add_chain_pilot.jsonl.gz, "
             "ioi_control: prompt_sets/ioi_control_pilot.jsonl.gz}",
             "cells:"]
    n = 0
    for task, layer, bracket in CELLS:
        target = canonical_l0(inv[str(layer)]["16k"])
        lines.append(f"  # {task} L{layer}: target L0 {target} (pilot 16k variant)")
        for w, l0, why in variants_for(inv, layer, bracket):
            if (only and w not in only) or w in exclude:
                continue
            role = "confirmatory" if w == "16k" and task in ("entity_track", "add_chain") else "exploratory"
            lines.append(f"  - {{task: {task}, layer: {layer}, sae: {{width: {w}, l0: {l0}, rule: explicit}}, role: {role}}}"
                         f"   # {why}; |log L0 ratio| {abs(__import__('math').log(l0 / target)):.2f}")
            n += 1
    if not n:
        return ""
    lines += ["n_train: 300", "n_test: 150", "filters: [f_none, f_A_correct, f_pilot]", "fit_filter: f_pilot",
              "conditions: [feat_A_errB, feat_A_meanPos, feat_A_zero]", "noise_seeds: [0]",
              "directions:", "  conditions: [repair]", "  ranks: [0, 1, 2]", "  estimators: [pca_pooled, answer_sep]",
              "  sources: [same_task]", "  random_seeds: 0", "  r_max: 32",
              "generic: {set: generic/pile10k_100x128.json, skip_positions: 4}",
              "generic_l0: true                    # realized L0 and error energy of every SAE on 100 x 124 generic tokens",
              "bootstrap: 1000", "seed: 0", "notes:",
              "  - \"Width persistence (PREREGISTRATION): ratio between 16k and the widest available SAE at matched realized "
              "L0 (within 25%); the 16k cells are the confirmatory ones, other widths exploratory.\"",
              "  - \"SAEs >= 524k are held in bf16 (pilot rule, profile sae_bf16_min_width); smaller ones in fp32.\""]
    return "\n".join(lines) + "\n"


E5_CELLS = [("entity_track", 12), ("add_chain", 18)]
E5_WIDE = "262k"                       # matched-L0 wide SAE; falls back to the widest width at a layer without it


def render_e5(inv_meta: dict) -> str:
    inv = inv_meta["inventory"]
    lines = ["# E5 (P1): subthreshold add-back. JumpReLU zeroes features with 0 < z < theta; does adding A's near-threshold",
             "# features back (alpha*theta <= z < theta) close the features-only gap? 16k (pilot) and the matched-L0 wide SAE.",
             "# GENERATED by scripts/make_e4_config.py from configs/sae_inventory.json "
             f"(revision {inv_meta['revision'][:12]}); edit the script, not this file.",
             "exp_id: E5", "name: subthreshold_addback",
             "description: subthresh(alpha) = x_hat_A + sum_{alpha*theta <= z < theta, z > 0} z W_dec + error slot (eps_B or "
             "eps_bar_pos), all near-threshold latents or a greedy train-fitted set of k <= 10.",
             f"model_revision: {MODEL_REVISION}",
             "prompt_sets: {entity_track: prompt_sets/entity_track_pilot.jsonl.gz, add_chain: prompt_sets/add_chain_pilot.jsonl.gz}",
             "cells:"]
    for task, layer in E5_CELLS:
        ws = inv[str(layer)]
        target = canonical_l0(ws["16k"])
        wide = E5_WIDE if E5_WIDE in ws else max(ws, key=parse_width)
        m = match_l0(target, ws[wide])
        lines.append(f"  - {{task: {task}, layer: {layer}, sae: {{width: 16k, l0: {target}, rule: explicit}}, role: confirmatory}}"
                     "   # pilot (canonical)")
        note = "matched L0" if wide == E5_WIDE else f"matched L0; no {E5_WIDE} at L{layer}, widest available"
        lines.append(f"  - {{task: {task}, layer: {layer}, sae: {{width: {wide}, l0: {m['closest']}, rule: explicit}}, "
                     f"role: exploratory}}   # {note} (target {target})")
    lines += ["n_train: 300", "n_test: 150", "filters: [f_none, f_A_correct, f_pilot]", "fit_filter: f_pilot",
              "conditions: [feat_A_errB, feat_A_meanPos, feat_A_zero]      # references: alpha -> 1 and no add-back",
              "noise_seeds: [0]",
              "subthresh:",
              "  alphas: [0.5, 0.7, 0.8, 0.9, 0.95]",
              "  slot_errors: [B, meanPos]           # x_hat_A + add-back + eps_B  |  ... + eps_bar_pos (train mean error)",
              "  greedy_ks: [1, 2, 5, 10]            # greedy latent sets fitted on train pairs at greedy_alpha",
              "  greedy_alpha: 0.5",
              "bootstrap: 1000", "seed: 0", "notes:",
              "  - \"Per-pair key: condition subthresh, estimator all|greedy, source 'alpha=<a>|slot=<B|meanPos>', r = greedy k "
              "(0 = all near-threshold latents). Greedy latent ids and objective trace: <run>/subthresh/*.json.\"",
              "  - \"Greedy objective (model-free, train only): minimise sum over train span rows of ||(eps_A - eps_B) - "
              "add-back(L)||^2, i.e. move feat_A_errB towards x_A in the residual stream.\""]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    meta = json.loads((ROOT / "configs" / "sae_inventory.json").read_text())
    files = {
        ROOT / "configs" / "experiments" / "E4.yaml": render(
            meta, set(), SEPARATE, "E4", "width_l0_matched",
            "E4 (P1): matched-L0 widths. OT L12 primary (closest + bracketing L0 per width); RS L18 and IOI L12 secondary "
            "(closest only). 1m: see E4_1m.yaml."),
        ROOT / "configs" / "experiments" / "E4_1m.yaml": render(
            meta, SEPARATE, set(), "E4", "width_l0_matched_1m",
            "E4 (P1, run only if time permits): the 1m SAEs at L0 matched to the pilot 16k (~9.7 GB host RAM in bf16, "
            "streamed block-wise; the model is never on the GPU at the same time)."),
        ROOT / "configs" / "experiments" / "E5.yaml": render_e5(meta),
    }
    bad = 0
    for p, text in files.items():
        if a.check:
            if not p.exists() or p.read_text() != text:
                print(f"{p.relative_to(ROOT)} is out of date: rerun scripts/make_e4_config.py")
                bad += 1
        else:
            p.write_text(text)
            print(f"wrote {p.relative_to(ROOT)} ({text.count('- {task')} cells)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
