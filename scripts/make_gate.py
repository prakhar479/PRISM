#!/usr/bin/env python
"""DEV: the RQ1 gate table (handoff 11, phase 2b) from ingested runs only. It computes the preregistered quantity;
the GO / NO-GO decision is the humans' (PREREGISTRATION.md).

    python scripts/make_gate.py [--n-boot 10000]

RQ1 (PREREGISTRATION.md): GO for a confirmatory cell if, on fresh template families, the flip-rate shortfall of
feat_A_meanPos relative to full_A is >= 10 points with a 95% CI excluding 0. The gate uses filter f_pilot (humans,
2026-11-03) and mean errors fitted on fresh families (fit_families = fresh, humans, 2026-11-03); other filters and
pilot-fitted mean errors on fresh families are reported as sensitivity rows.

Rows: every complete run with feat_A_meanPos and full_A on a confirmatory (task, layer) at 16k, split by evaluation
group (fresh families vs pilot families). Only E3 rows evaluated on fresh families are the gate ('gate'); rows on the
pilot templates are labelled 'reference (pilot templates, not the gate)'. Per row: shortfall with a pair-level 95% CI
and, on fresh families, a family-clustered 95% CI; criterion_met_* = shortfall >= 0.10 and CI lower bound > 0.
Writes tables/RQ1_gate.csv (all baselines and metrics, for context) and tables/RQ1_gate.md (preregistered rows).
"""
import argparse
import json
from pathlib import Path

import _bootstrap  # noqa: F401
import pandas as pd

from harness import e8
from harness import families as F
from harness.profile import REPO_ROOT, load_profile

THRESHOLD = 0.10
CONDITION = "feat_A_meanPos"
GATE_FILTER = "f_pilot"        # humans' decision 2026-11-03 (DECISIONS.md); other filters are sensitivity rows
GATE_FIT = "fresh"             # humans' decision 2026-11-03: mean errors fitted on fresh families; pilot-fit = sensitivity


def gate_rows(m: dict, pp: pd.DataFrame, n_boot: int) -> list:
    pp = pp.assign(fit_families=pp["fit_families"] if "fit_families" in pp else "pilot")
    pp = pp.assign(eval_group=pp["family"].map(lambda f: "pilot" if F.is_pilot(str(f)) else "fresh"))
    out = []
    for (task, layer, sae, fit, grp), g in pp.groupby(["task", "layer", "sae", "fit_families", "eval_group"]):
        if (task, int(layer)) not in e8.CONFIRMATORY or not str(sae).startswith(f"L{int(layer)}_16k"):
            continue
        if not {"full_A", CONDITION} <= set(g.condition):
            continue
        is_gate = grp == "fresh"
        for flt in m["config"].get("filters", ["f_pilot"]):
            pair_rows, _, _ = e8.analyse_cell(g, flt, n_boot)
            clus = {}
            if is_gate and g["family"].nunique() > 1:
                c_rows, _, _ = e8.analyse_cell(g, flt, n_boot, cluster_col="family")
                clus = {(r["metric"], r["condition"], r["seed"]): r for r in c_rows}
            for r in pair_rows:
                c = clus.get((r["metric"], r["condition"], r["seed"]), {})
                if not is_gate:
                    use = "reference (pilot templates, not the gate)"
                elif flt == GATE_FILTER and fit == GATE_FIT:
                    use = "gate"
                else:
                    use = f"sensitivity (filter {flt}, fit {fit}; not the gate)"
                row = {"use": use,
                       "exp_id": m["exp_id"], "run_hash": m["run_hash"], "task": task, "layer": int(layer), "sae": sae,
                       "fit_families": fit, "eval_group": grp, "families": ",".join(sorted(g["family"].astype(str).unique())),
                       **{k: r[k] for k in ("filter", "metric", "condition", "seed", "full_A", "value", "n_pairs",
                                            "flip_n_eligible")},
                       "shortfall": r["gap"], "lo_pairs": r["gap_lo"], "hi_pairs": r["gap_hi"],
                       "lo_family_cluster": c.get("gap_lo"), "hi_family_cluster": c.get("gap_hi")}
                row["criterion_met_pairs"] = bool(row["shortfall"] >= THRESHOLD and row["lo_pairs"] > 0)
                row["criterion_met_family_cluster"] = (bool(row["shortfall"] >= THRESHOLD and row["lo_family_cluster"] > 0)
                                                       if c else None)
                out.append(row)
    return out


def md(df: pd.DataFrame) -> str:
    d = df[(df.metric == e8.PRIMARY) & (df.condition == CONDITION)].copy()
    d["_o"] = d.use.map(lambda u: 0 if u == "gate" else 1 if u.startswith("sensitivity") else 2)
    d = d.sort_values(["_o", "task", "fit_families", "filter"])
    f = lambda x: "--" if x is None or pd.isna(x) else f"{100 * x:.1f}"
    lines = ["# RQ1 gate table (generated by scripts/make_gate.py; the decision is the humans')", "",
             f"Preregistered quantity: flip rate (full_A) - flip rate ({CONDITION}), in points. Criterion: >= "
             f"{100 * THRESHOLD:.0f} points with the 95% CI excluding 0. Only rows marked `gate` (fresh families, E3, "
             f"filter {GATE_FILTER}, mean errors fitted on {GATE_FIT} families) are the gate.", "",
             "| use | task | L | fit families | eval | filter | n pairs (eligible) | full_A | meanPos | shortfall | "
             "95% CI pairs | 95% CI family-cluster | criterion met (pairs / cluster) | run |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for _, x in d.iterrows():
        cm = f"{x.criterion_met_pairs} / {x.criterion_met_family_cluster if x.criterion_met_family_cluster is not None else '--'}"
        lines.append(f"| {x.use} | {x.task} | {x.layer} | {x.fit_families} | {x.eval_group} | {x['filter']} | "
                     f"{x.n_pairs} ({x.flip_n_eligible}) | {f(x.full_A)} | {f(x.value)} | {f(x.shortfall)} | "
                     f"[{f(x.lo_pairs)}, {f(x.hi_pairs)}] | [{f(x.lo_family_cluster)}, {f(x.hi_family_cluster)}] | {cm} | "
                     f"`{x.run_hash}` |")
    if not (d.use == "gate").any():
        lines += ["", "**No E3 (fresh-family) run has been ingested yet: there is no gate row.** The rows above are the "
                      "same quantity on the pilot templates, for reference only."]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-boot", type=int, default=10_000)
    ap.add_argument("--profile", default=None)
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    prof = load_profile(a.profile or "dev")
    rows = []
    for man in sorted(prof.root("runs_root").glob("E*/*/manifest.json")):
        m = json.loads(man.read_text())
        if m.get("smoke") or m.get("tiny") or m.get("status") != "complete":
            continue
        pp = pd.read_parquet(man.parent / "per_pair.parquet")
        if CONDITION in set(pp.condition):
            rows += gate_rows(m, pp, a.n_boot)
    out = Path(a.out) if a.out else REPO_ROOT / "tables"
    out.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame(rows)
    df.to_csv(out / "RQ1_gate.csv", index=False)
    (out / "RQ1_gate.md").write_text(md(df) if len(df) else "# RQ1 gate table\n\nNo run with feat_A_meanPos.\n")
    print(f"RQ1_gate: {len(df)} rows ({int((df.use == 'gate').sum()) if len(df) else 0} gate rows) -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
