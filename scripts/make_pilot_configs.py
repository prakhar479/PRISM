#!/usr/bin/env python
"""Write the breadth pilot's experiment configs (configs/pilot/P*.yaml) from one place (docs/PILOT_BREADTH_PLAN.md).

    python scripts/make_pilot_configs.py            # (re)write every config; --check: fail if a committed config differs

The configs are generated so that cell lists (layers x families x dictionaries), L0 matching and estimator grids are
computed, not typed. Dictionaries for P2 / P8 / P9 come from configs/dict_registry.yaml by their `group` field.
Everything here is exploratory (role: exploratory); none of it touches a preregistered answer.
"""
import argparse
import json
import math
import sys
from pathlib import Path

import yaml

import _bootstrap  # noqa: F401

from harness.profile import REPO_ROOT

OUT = REPO_ROOT / "configs" / "pilot"
REV = "c5ebcd40d208330abc697524c919956e692655cf"            # gemma-2-2b
G3_REV = "fcf18a2a879aab110ca39f8bffbccd5d49d8eb29"         # gemma-3-1b-pt (HF commit, 2026-11-22)
PS = {"add_chain": "prompt_sets/add_chain_pilot.jsonl.gz", "people_cities": "prompt_sets/people_cities_en.jsonl.gz",
      "pc_p1": "prompt_sets/people_cities_p1.jsonl.gz", "ot_p11": "prompt_sets/entity_track_p11.jsonl.gz"}
OT_FAMS = ["ot_placed_dest", "ot_bin_dest", "ot_drawer_dest"]
INV = json.loads((REPO_ROOT / "configs" / "sae_inventory.json").read_text())["inventory"]
REG_PATH = REPO_ROOT / "configs" / "dict_registry.yaml"


def canonical(layer, width="16k"):
    v = INV[str(layer)][width]
    return min(v, key=lambda x: (abs(x - 100), x))


def matched(layer, width, target_width="16k"):
    """Variant of `width` whose L0 is closest (log ratio) to the canonical `target_width` variant (E4/E20's rule)."""
    t = canonical(layer, target_width)
    return min(INV[str(layer)][width], key=lambda v: (abs(math.log(v / t)), v))


def gs(layer, width="16k", **kw):
    l0 = canonical(layer) if width == "16k" else matched(layer, width)
    return {"width": width, "l0": l0, "rule": "explicit", **kw}


def registry(group):
    if not REG_PATH.exists():
        return {}
    reg = (yaml.safe_load(REG_PATH.read_text()) or {}).get("dictionaries") or {}
    return {k: v for k, v in sorted(reg.items()) if v.get("group") == group}


def base(exp_id, name, description, prompt_sets, **kw):
    d = {"exp_id": exp_id, "name": name, "description": description, "model_revision": REV, "prompt_sets": prompt_sets,
         "n_train": 300, "n_test": 150, "filters": ["f_pilot"], "fit_filter": "f_pilot", "bootstrap": 1000, "seed": 0,
         "notes": ["breadth pilot (docs/PILOT_BREADTH_PLAN.md): exploratory, post hoc; generated by scripts/make_pilot_configs.py"]}
    d.update(kw)
    return d


def pc(layer, sae, fam="pc_en"):
    return {"task": "people_cities", "layer": layer, "sae": sae, "role": "exploratory", "fit_families": [fam], "eval_families": [fam]}


def ot(layer, sae):
    return {"task": "entity_track", "layer": layer, "sae": sae, "role": "exploratory", "fit_families": OT_FAMS, "eval_families": OT_FAMS}


def rs(layer, sae):
    return {"task": "add_chain", "layer": layer, "sae": sae, "role": "exploratory"}


def configs() -> dict:
    out = {}
    # ---------------------------------------------------------------- P0: protocol (DAS objective, seed, write-back, nulls)
    das0 = [f"das{k}v2_{o}_s{s}" for k in (4, 8, 16) for o in ("ce", "ld", "kl") for s in (0, 1, 2)] + ["das4", "das8"]
    out["P0"] = base("P0", "protocol_hardening",
                     "Do the RS L18 / PC L12 feature-capture numbers survive the DAS objective (ce / ld / kl), the seed (3 independent "
                     "starts), held-out validity, the write-back operator (subspace vs code level) and matched random nulls?",
                     {"add_chain": PS["add_chain"], "people_cities": PS["people_cities"]},
                     cells=[rs(18, gs(18)), pc(12, gs(12))],
                     conditions=["feat_A_errB", "feat_A_meanPos", "feat_A_noise", "feat_A_covnoise", "feat_B_noise"],
                     directions={"conditions": ["feat_A_along_U", "full_along_U", "feat_codes_along_U"], "ranks": [4, 8, 16],
                                 "estimators": das0, "sources": ["same_task"], "random_seeds": 20, "r_max": 16})
    # ---------------------------------------------------------------- P1: binding blind spot (content vs swap vs query)
    cells = []
    for fam in ("pc_en", "pc_en_swap", "pc_en_query"):
        for L in (8, 12, 16):
            cells += [pc(L, gs(L), fam), pc(L, gs(L, "65k"), fam)]
    out["P1"] = base("P1", "binding_blind_spot",
                     "At matched rank, do SAE features carry the pairing (binding swap) or the pointer (query swap) less than the "
                     "content (which city)? Three counterfactual families on one template, L8/12/16, 16k and 65k at matched L0.",
                     {"people_cities": PS["pc_p1"]}, cells=cells,
                     conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA"],
                     directions={"conditions": ["feat_A_along_U", "full_along_U", "repair"], "ranks": [1, 2, 4, 8, 16, 32, 64],
                                 "estimators": ["das4v2_kl", "das8v2_kl", "das16v2_kl", "pca_pooled"], "sources": ["same_task"],
                                 "random_seeds": 10, "r_max": 64})
    # ---------------------------------------------------------------- P11: object tracking without a default answer
    out["P11"] = base("P11", "object_tracking_no_default",
                      "Object tracking where both runs move the queried object (no answer fixed by the prefix): causal split, "
                      "error-only, noise controls and DAS capture at L8/12/16; the per-pair outcome also records the fallback box.",
                      {"entity_track": PS["ot_p11"]}, cells=[ot(L, gs(L)) for L in (8, 12, 16)],
                      conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA", "feat_B_noise", "feat_A_noise"],
                      directions={"conditions": ["feat_A_along_U", "full_along_U", "repair"], "ranks": [1, 2, 4, 8, 16],
                                  "estimators": ["das4v2_kl", "das8v2_kl", "pca_pooled"], "sources": ["same_task"],
                                  "random_seeds": 10, "r_max": 16})
    # ---------------------------------------------------------------- P2: dictionary-family sweep at fixed sites
    # PC and RS at L12 only (stage-2 caches x_hat for every dictionary: ~0.3 GB per dictionary on these sets, ~1.6 GB on the
    # object-tracking set, so object tracking stays in P11 / P4 / P7); the code-level write-back is P0's question.
    cells = []
    l12 = [gs(12, w) for w in ("16k", "65k", "262k")] + [{"dict": n} for n in registry("p2_L12")] \
        + [{"dict": "trained:frozendec_L12_16k", "width": "16k"}] + [{"dict": n} for n in registry("p9_L12")]   # P9 folded in
    for sae in l12:
        cells += [pc(12, sae), rs(12, sae)]
    for w in ("16k", "65k", "1m"):
        cells.append(rs(19, gs(19, w)))
    for name in registry("p2_L19"):
        cells.append(rs(19, {"dict": name}))
    cells.append(rs(19, {"dict": "trained:frozendec_L19_16k", "width": "16k"}))
    out["P2"] = base("P2", "dictionary_family_sweep",
                     "Same sites, many dictionaries: Gemma Scope widths, SAEBench architectures x widths x two L0s (registry group "
                     "p2_L12), a frozen-random-decoder control and (P9) the temporal SAE; one fixed DAS subspace per cell scores every "
                     "dictionary. Fidelity on generic text: realised L0 / FVU here (generic_l0), CE in job PF_P2.",
                     {"people_cities": PS["people_cities"], "add_chain": PS["add_chain"]},
                     cells=cells, generic={"set": "generic/pile10k_100x128.json", "skip_positions": 4}, generic_l0=True,
                     conditions=["feat_A_errB", "feat_A_meanPos"],
                     directions={"conditions": ["feat_A_along_U", "full_along_U"], "ranks": [8],
                                 "estimators": ["das8v2_kl"], "sources": ["same_task"], "random_seeds": 5, "r_max": 8})
    # ---------------------------------------------------------------- P4 (+P6): do logit-level fixes restore task state?
    cells = []
    for maker, L in ((rs, 18), (pc, 12), (ot, 12)):
        cells += [maker(L, gs(L)), maker(L, gs(L, addon="lin")), maker(L, gs(L, addon="pcx24")), maker(L, gs(L, addon="pcx1")),
                  maker(L, {"dict": f"trained:klft_L{L}_16k", "width": "16k"})]
    out["P4"] = base("P4", "logit_fixes_vs_state",
                     "Gemma Scope 16k vs its KL+MSE fine-tune, its linear error add-on (Engels' predictable error; P6) and dense "
                     "low-rank add-backs (top-24 / top-1 uncentered PCs of x; Deng's scaffold): task gaps here, CE gaps in PF_P4.",
                     {"add_chain": PS["add_chain"], "people_cities": PS["people_cities"], "entity_track": PS["ot_p11"]},
                     cells=cells, generic={"set": "generic/pile10k_6000x128_skip100.json", "skip_positions": 4},
                     conditions=["feat_A_errB", "feat_A_meanPos"],
                     directions={"conditions": ["feat_A_along_U", "full_along_U"], "ranks": [8], "estimators": ["das8v2_kl"],
                                 "sources": ["same_task"], "random_seeds": 5, "r_max": 8})
    # ---------------------------------------------------------------- P5: magnitude vs periodic structure of the running sum
    cells = [rs(L, gs(L, w)) for L in (16, 18, 19) for w in ("16k", "65k")] + [rs(19, gs(19, "1m"))]
    out["P5"] = base("P5", "magnitude_goes_dark",
                     "Running sum: is the state the SAE misses the smooth magnitude axis (ridge line of the value) rather than the "
                     "periodic digit code (Fourier planes, periods 2/5/10)? Feature share and causal effect per component, and "
                     "which component carries the far-donor resampled-error effect; widths 16k/65k (+1m at L19).",
                     {"add_chain": PS["add_chain"]}, cells=cells,
                     conditions=["feat_A_errB", "feat_A_meanPos", "feat_A_resampC_sameAns", "feat_A_resampC_diffAns"],
                     directions={"conditions": ["feat_A_along_U", "full_along_U", "resampU_sameAns", "resampU_diffAns"],
                                 "ranks": [1, 2, 4, 8],
                                 "estimators": ["ridge_value", "fourier_T10", "fourier_T5", "fourier_T2", "das4v2_kl", "das8v2_kl", "pca_pooled"],
                                 "sources": ["same_task"], "random_seeds": 10, "r_max": 8})
    # ---------------------------------------------------------------- P7: sensitivity-chosen vs variance-chosen error directions
    out["P7"] = base("P7", "sensitivity_not_variance",
                     "Repair with error directions chosen by output sensitivity (first-order optimal grad_err; grad_pooled) vs by "
                     "variance (pca_pooled, answer_sep) vs DAS, ranks 1-16, matched random nulls. English splice-vs-noise costs: job E23_en.",
                     {"add_chain": PS["add_chain"], "people_cities": PS["people_cities"], "entity_track": PS["ot_p11"]},
                     cells=[rs(18, gs(18)), pc(12, gs(12)), ot(12, gs(12))],
                     conditions=["feat_A_errB", "feat_A_meanPos"],
                     directions={"conditions": ["repair", "feat_A_along_U"], "ranks": [1, 2, 4, 8, 16],
                                 "estimators": ["grad_err", "grad_pooled", "pca_pooled", "answer_sep", "das8v2_kl"],
                                 "sources": ["same_task"], "random_seeds": 20, "r_max": 16})
    # ---------------------------------------------------------------- P8: second model (Gemma 3 1B + Gemma Scope 2)
    g3 = registry("p8_g3")
    if g3:
        cells = []
        for name, e in g3.items():
            L = int(e["layer"])
            cells += [rs(L, {"dict": name}), pc(L, {"dict": name}), ot(L, {"dict": name})]
        out["P8"] = base("P8", "second_model_gemma3",
                         "Gemma 3 1B with Gemma Scope 2 residual SAEs (registry group p8_g3): capability (keep rates in the cell checks), "
                         "the causal split and DAS capture for running sum, people-cities and object tracking.",
                         {"add_chain": "prompt_sets/add_chain_p8_g3.jsonl.gz", "people_cities": "prompt_sets/people_cities_p1_g3.jsonl.gz",
                          "entity_track": "prompt_sets/entity_track_p11_g3.jsonl.gz"},
                         model="gemma-3-1b-pt", model_revision=G3_REV, cells=cells,
                         conditions=["feat_A_errB", "feat_A_meanPos", "feat_B_errA", "feat_B_noise"],
                         directions={"conditions": ["feat_A_along_U", "full_along_U"], "ranks": [4, 8],
                                     "estimators": ["das4v2_kl", "das8v2_kl"], "sources": ["same_task"], "random_seeds": 5, "r_max": 8})
        for c in out["P8"]["cells"]:
            if c["task"] == "people_cities":
                c["fit_families"] = c["eval_families"] = ["pc_en"]
            if c["task"] == "add_chain":
                c["fit_families"] = c["eval_families"] = ["rs_en", "rs_plus", "rs_story"]
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    bad = []
    for k, d in configs().items():
        text = "# GENERATED by scripts/make_pilot_configs.py: edit the script, not this file\n" + yaml.safe_dump(d, sort_keys=False, width=140)
        p = OUT / f"{k}.yaml"
        if a.check:
            if not p.exists() or p.read_text() != text:
                bad.append(p.name)
            continue
        p.write_text(text)
        from harness.config import ExpConfig
        ExpConfig.load(p)                                   # validates
        print(f"{p.relative_to(REPO_ROOT)}: {len(d['cells'])} cells")
    if bad:
        print("out of date:", bad)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
