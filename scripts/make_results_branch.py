#!/usr/bin/env python
"""Build (or advance) the clean results branch: every finished, non-smoke run, every generated table, the analysis digests and
the documents needed to read them, and nothing else (no code, no parts/, no caches).

    python scripts/make_results_branch.py --runs <runs_root> --tables <tables dir> [--analysis <dir>] [--dry-run]

Layout of the branch (default name results-consolidated):
    README.md                  what is here, provenance, how each table was made, preregistered vs exploratory
    INDEX.json / INDEX.md      one row per run: experiment, run hash, status, commit, tags, created, machine, rows, notes
    runs/<exp>/<run_hash>/     manifest.json, per_pair.parquet, summary.*, directions/, ... (parts/ and smoke/tiny runs left out)
    runs/_queue/<tag>/         queue state of each release (status, machine, logs)
    tables/                    CSV / MD tables (scripts/make_tables.py, make_gate.py, make_e8.py, make_e4.py, ...)
    analysis/                  exploratory digests and reports (each file says what it is)
    docs/                      PREREGISTRATION.md, PREREGISTRATION_ADDENDUM.md, DECISIONS.md, tables/SCHEMA.md as of the source commit
Built with git plumbing (a temporary index + commit-tree), so the working tree is never touched; each build is a new commit on
top of the previous one (history of result snapshots). The commit is signed unless --no-sign.
"""
import argparse
import datetime as dt
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ["PREREGISTRATION.md", "PREREGISTRATION_ADDENDUM.md", "DECISIONS.md", "tables/SCHEMA.md", "RESULTS_INDEX.md"]
MAX_FILE = 95 * 2 ** 20
SKIP_DIRS = {"parts", "__pycache__"}


def git(*args, input=None, env=None) -> str:
    r = subprocess.run(["git", "-C", str(ROOT), *args], input=input, capture_output=True, env={**os.environ, **(env or {})})
    if r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {r.stderr.decode().strip()}")
    return r.stdout.decode()


def blob(data: bytes) -> str:
    return git("hash-object", "-w", "--stdin", input=data).strip()


def tags_of(commit: str):
    try:
        return git("tag", "--points-at", commit).split()
    except SystemExit:
        return []


def collect_runs(root: Path):
    files, index = [], []
    for man in sorted(root.glob("E*/*/manifest.json")):
        m = json.loads(man.read_text())
        d = man.parent
        keep = not (m.get("smoke") or m.get("tiny")) and m.get("status") == "complete"
        commit = (m.get("git") or {}).get("commit", "")
        pp = d / "per_pair.parquet"
        rows = None
        if pp.exists():
            import pyarrow.parquet as pq
            rows = pq.ParquetFile(pp).metadata.num_rows
        index.append({"exp": m.get("exp_id"), "run_hash": m.get("run_hash"), "status": m.get("status"), "smoke": bool(m.get("smoke")),
                      "included": keep, "name": (m.get("config") or {}).get("name"), "commit": commit[:12],
                      "tags": ",".join(tags_of(commit)) if commit else "", "created": m.get("created", ""),
                      "machine": (m.get("machine") or {}).get("gpu_name") or (m.get("machine") or {}).get("device"),
                      "per_pair_rows": rows, "table": m.get("table"), "note": m.get("finalize_note", "")})
        if not keep:
            continue
        for f in sorted(d.rglob("*")):
            rel = f.relative_to(d)
            if f.is_file() and not (set(rel.parts) & SKIP_DIRS) and ".tmp." not in f.name:
                files.append((f, Path("runs") / d.parent.name / d.name / rel))
    for q in sorted((root / "_queue").glob("*")):
        for f in sorted(q.rglob("*")):
            if f.is_file():
                files.append((f, Path("runs/_queue") / f.relative_to(root / "_queue")))
    return files, index


def index_md(index):
    L = ["# Run index", "", "| exp | run | included | status | name | commit | tags | created | machine | per-pair rows | note |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in index:
        L.append(f"| {r['exp']} | `{r['run_hash']}` | {'yes' if r['included'] else 'no (smoke/tiny/incomplete)'} | {r['status']} | {r['name']} | "
                 f"`{r['commit']}` | {r['tags']} | {r['created']} | {r['machine']} | {r['per_pair_rows'] or ''} | {r['note'][:80]} |")
    return "\n".join(L) + "\n"


README = """# PRISM results (clean data branch)

Generated by `scripts/make_results_branch.py` from `{src_branch}@{src}` on {created}. Data only: the code that produced every
file is on the `harness` branch at the commit named in each run's `manifest.json` (`git.commit`) and, for tables, at the source
commit above. Do not edit here; regenerate.

## What is here
- `runs/<exp>/<run_hash>/`: every complete, non-smoke run ({n_runs} runs). `per_pair.parquet` = one row per (pair, condition);
  `summary.*` = per-cell summaries; `manifest.json` = config, profile, git commit, packages, machine, timings. `parts/` (the
  per-unit shards that per_pair.parquet merges) are left out. `INDEX.md` lists every run found, including excluded ones and why.
- `tables/`: generated tables; columns in `docs/tables/SCHEMA.md`.
- `analysis/`: exploratory digests. They are NOT preregistered and carry no multiplicity correction; each file says so.
- `docs/`: the preregistration (and the draft addendum), DECISIONS.md, the table schema, as of the source commit.

## Preregistered vs exploratory
Preregistered (PREREGISTRATION.md): RQ1 gate (`tables/RQ1_gate.*`, rows marked `gate`), repair specificity (`tables/E8_*`,
confirmatory cells), width persistence (`tables/E4_width_persistence.csv`, rows with `prereg_row = True`). Under
PREREGISTRATION_ADDENDUM.md (frozen 2026-11-16): E9 running sum L18 (`tables/final/E9_illusion.csv`, role confirmatory), E10 Q2
running sum L18 (`tables/final/E10_steering.csv`, `q2_both`), M1 (`tables/final/E12_fidelity_lang.csv`), the capability gates
(`tables/final/E13_behaviour_lang.csv`, test split), M2/M3 on readable rows (`tables/final/E14_lang_gap.csv`,
`E14_m3_transfer.csv`; all multilingual work is exploratory by the addendum). Everything else is exploratory or descriptive.
GO / NO-GO decisions are the humans' and are not recorded in the tables. Written analysis: `analysis/final_pass_results.md`.

## Provenance notes
- Release 2 (E3, E4, E5, E8) was computed on gnode077 at commit 31713f8 (= tag run-20261114-1 + a 2-line sbatch change) and
  finalized on DEV from the committed parts because the server's CPU finalize jobs failed; see each manifest's `finalize_note`
  and `finalize_checks`, and DECISIONS.md (2026-11-16).
- PREREGISTRATION.md was still unfrozen when the release-2 results were first read (DECISIONS.md 2026-11-16).
- Release 3 + final pass (E9-E16, queue complete-server) ran on gnode084 (4 GPUs) at commit 14e7e1f = tag run-20261117-2 + a
  2-line `#SBATCH` node/GPU change; ingested with --allow-untagged (DECISIONS.md 2026-11-18). Finalized on the server.
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--runs", required=True)
    ap.add_argument("--tables", required=True)
    ap.add_argument("--analysis", default=None)
    ap.add_argument("--branch", default="results-consolidated")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--no-sign", action="store_true")
    a = ap.parse_args()
    src = git("rev-parse", "HEAD").strip()
    src_branch = git("rev-parse", "--abbrev-ref", "HEAD").strip()
    files, index = collect_runs(Path(a.runs))
    for f in sorted(Path(a.tables).rglob("*")):
        if f.is_file():
            files.append((f, Path("tables") / f.relative_to(a.tables)))
    if a.analysis:
        for f in sorted(Path(a.analysis).rglob("*")):
            if f.is_file():
                files.append((f, Path("analysis") / f.relative_to(a.analysis)))
    for d in DOCS:
        if (ROOT / d).exists():
            files.append((ROOT / d, Path("docs") / d))
    big = [(str(arc), f.stat().st_size) for f, arc in files if f.stat().st_size > MAX_FILE]
    if big:
        raise SystemExit(f"files over {MAX_FILE >> 20} MiB (GitHub refuses > 100 MiB): {big}")
    created = dt.datetime.now().isoformat(timespec="seconds")
    n_runs = sum(r["included"] for r in index)
    gen = {"README.md": README.format(src_branch=src_branch, src=src[:10], created=created, n_runs=n_runs).encode(),
           "INDEX.md": index_md(index).encode(), "INDEX.json": json.dumps(index, indent=1).encode(),
           "SOURCE.json": json.dumps({"source_commit": src, "source_branch": src_branch, "created": created,
                                      "files": len(files) + 4}, indent=1).encode()}
    size = sum(f.stat().st_size for f, _ in files)
    print(f"{len(files)} files ({size / 2**20:.1f} MiB), {n_runs} runs included of {len(index)} found")
    if a.dry_run:
        for f, arc in files:
            if "runs/" not in str(arc) or str(arc).endswith("manifest.json"):
                print("  ", arc)
        return 0
    with tempfile.TemporaryDirectory() as td:
        env = {"GIT_INDEX_FILE": str(Path(td) / "index")}
        git("read-tree", "--empty", env=env)
        for f, arc in files:
            git("update-index", "--add", "--cacheinfo", f"100644,{blob(f.read_bytes())},{arc.as_posix()}", env=env)
        for name, data in gen.items():
            git("update-index", "--add", "--cacheinfo", f"100644,{blob(data)},{name}", env=env)
        tree = git("write-tree", env=env).strip()
    parent = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--verify", "-q", f"refs/heads/{a.branch}"],
                            capture_output=True, text=True).stdout.strip()
    msg = f"Results snapshot from {src_branch}@{src[:10]}: {n_runs} runs, tables, analysis\n\nSource-Commit: {src}\n"
    cmd = ["commit-tree", tree, "-m", msg] + (["-p", parent] if parent else []) + ([] if a.no_sign else ["-S"])
    commit = git(*cmd).strip()
    git("update-ref", f"refs/heads/{a.branch}", commit, *([parent] if parent else []))
    print(f"branch {a.branch} -> {commit[:10]}; push with: git push origin {a.branch}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
