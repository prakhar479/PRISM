#!/usr/bin/env python
"""Automated checks of the language template packs (harness/langfamilies.py) and the review file for the humans.

    python scripts/validate_templates.py                     # check, print, write data/lang/templates_review.md
    python scripts/validate_templates.py --check             # exit 1 if any automated check fails (no file written)

Automated (tokenizer side only): NFC stability (so composed and decomposed forms of one letter cannot differ between templates and corpora), label / digit /
city answers are one token, every object an OT pair can swap has the same token count. What it CANNOT check is whether the sentences are grammatical and natural: a native
speaker has to read the sample prompts in the review file and tick the pack. A pack stays `validated: false` in the prompt sets
until `LF.VALIDATED[...]` is flipped by a human after that review.
"""
import argparse
import sys
import unicodedata
from pathlib import Path

import _bootstrap  # noqa: F401
from harness import families as F
from harness import langfamilies as LF
from harness.profile import REPO_ROOT

MODEL_REVISION = "c5ebcd40d208330abc697524c919956e692655cf"


def tokenizer():
    import glob
    from tokenizers import Tokenizer
    p = glob.glob(str(Path.home() / ".cache/huggingface/hub/models--google--gemma-2-2b/snapshots" / MODEL_REVISION / "tokenizer.json"))
    if not p:
        from huggingface_hub import hf_hub_download
        p = [hf_hub_download("google/gemma-2-2b", "tokenizer.json", revision=MODEL_REVISION)]
    return Tokenizer.from_file(p[0])


def strings_of(f):
    for k, v in vars(f).items():
        if isinstance(v, str):
            yield k, v
        elif isinstance(v, tuple):
            yield from ((k, x) for x in v if isinstance(x, str))


def check(tk):
    n = lambda s: len(tk.encode(s, add_special_tokens=False).ids)
    problems = []
    for task, fams in LF.FAMILIES.items():
        for fid, f in fams.items():
            for k, s in strings_of(f):
                if unicodedata.normalize("NFC", s) != s:
                    problems.append(f"{fid}.{k}: {s!r} is not NFC-stable")
            if task == "entity_track":
                if {n(" " + b) for b in f.labels} != {1}:
                    problems.append(f"{fid}: a box label is not one token")
                lens = {o: n(" " + o) for o in f.objects}
                if len(set(lens.values())) != 1:
                    problems.append(f"{fid}: objects have different token counts {lens}")
            elif task == "people_cities":
                multi = [c for c in f.cities if n(" " + c) != 1]
                if multi:
                    problems.append(f"{fid}: city answers not one token: {multi}")
            elif task == "add_chain" and {n(" " + str(d)) for d in range(10)} != {n(" 0")}:
                problems.append(f"{fid}: digits tokenise unevenly")
    return problems


def sample(task, fid, seed=7):
    p = F.generate_pairs(task, fid, 1, seed, split="review")[0]
    return p.clean_prompt, p.clean_target_str.strip(), p.corrupt_prompt, p.corrupt_target_str.strip()


def review_md(problems):
    L = ["# Template review (for a human; generated by scripts/validate_templates.py, do not edit by hand)", "",
         "Every pack below is a DRAFT written by the assistant. The automated checks only cover the tokenizer; they say nothing about",
         "grammar or naturalness. For each language please read the sample prompts, then tick the box and put your name and the date.",
         "To record a sign-off, set the pack to True in `harness/langfamilies.py: VALIDATED` (that flips `validated` in rebuilt prompt sets).", "",
         f"Automated checks: {'**all passed**' if not problems else '**FAILED:** ' + '; '.join(problems)}", ""]
    for lang in LF.LANGUAGES:
        L += [f"## {lang}", "", f"- [ ] reviewed by ______ on ______ (grammar, naturalness, no offensive content); packs: " +
              ", ".join(LF.family_id(t, lang) for t in LF.FAMILIES), ""]
        for task in LF.FAMILIES:
            fid = LF.family_id(task, lang)
            cp, ca, kp, ka = sample(task, fid)
            last = cp.split("\n")[-1]
            L += [f"**{fid}**: `{last}` -> **{ca}**", "",
                  f"corrupt: `{kp.split(chr(10))[-1]}` -> {ka}", ""]
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    problems = check(tokenizer())
    for p in problems:
        print("PROBLEM:", p)
    if a.check:
        return 1 if problems else 0
    out = REPO_ROOT / "data" / "lang" / "templates_review.md"
    out.write_text(review_md(problems))
    print(f"{'all automated checks passed' if not problems else str(len(problems)) + ' problems'}; review file: {out}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
